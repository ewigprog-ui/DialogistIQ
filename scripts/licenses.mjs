/**
 * License check and third-party notices for everything we distribute
 * (PROJECT_BIBLE.md §13.4).
 *
 *   node scripts/licenses.mjs check     → exits 1 if any dependency violates licenses.policy.json
 *   node scripts/licenses.mjs notices   → writes THIRD_PARTY_NOTICES.md
 *
 * Sources: production npm dependencies (`pnpm licenses list --prod`) and all Rust crates
 * in src-tauri/Cargo.lock (`cargo metadata`). Rust build-time and other-platform crates
 * are included on purpose: stricter is safer.
 */
import { execSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { findViolations } from "./lib/license-policy.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OWN_PACKAGES = new Set(["studio"]);

/** Runs a fixed command line (no user input involved) and returns stdout. */
function run(commandLine, cwd = ROOT) {
  return execSync(commandLine, {
    cwd,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
    stdio: ["ignore", "pipe", "inherit"],
  });
}

function npmPackages() {
  const byLicense = JSON.parse(run("pnpm licenses list --prod --json"));
  const out = [];
  for (const [license, entries] of Object.entries(byLicense)) {
    for (const e of entries) {
      e.versions.forEach((version, i) => {
        out.push({
          ecosystem: "npm",
          name: e.name,
          version,
          license: e.license ?? license,
          dir: e.paths?.[i] ?? e.paths?.[0],
          homepage: e.homepage,
        });
      });
    }
  }
  return out;
}

function cargoPackages() {
  const meta = JSON.parse(run("cargo metadata --format-version 1 --locked", join(ROOT, "src-tauri")));
  return meta.packages
    .filter((p) => !OWN_PACKAGES.has(p.name))
    .map((p) => ({
      ecosystem: "cargo",
      name: p.name,
      version: p.version,
      license: p.license ?? (p.license_file ? `see ${p.license_file}` : ""),
      dir: dirname(p.manifest_path),
      homepage: p.repository ?? p.homepage,
    }));
}

function collect() {
  const packages = [...npmPackages(), ...cargoPackages()].filter((p) => !OWN_PACKAGES.has(p.name));
  packages.sort((a, b) => a.ecosystem.localeCompare(b.ecosystem) || a.name.localeCompare(b.name));
  return packages;
}

function loadPolicy() {
  return JSON.parse(readFileSync(join(ROOT, "licenses.policy.json"), "utf8"));
}

function check() {
  const packages = collect();
  const violations = findViolations(packages, loadPolicy());
  const counts = packages.reduce((acc, p) => ((acc[p.ecosystem] = (acc[p.ecosystem] ?? 0) + 1), acc), {});
  console.log(`Checked ${packages.length} packages (npm: ${counts.npm ?? 0}, cargo: ${counts.cargo ?? 0}).`);
  if (violations.length === 0) {
    console.log("✓ All licences comply with licenses.policy.json (PROJECT_BIBLE.md §13).");
    return;
  }
  console.error(`\n✗ ${violations.length} licence violation(s):`);
  for (const v of violations) {
    console.error(`  [${v.ecosystem}] ${v.name}@${v.version}  "${v.license}"  → ${v.reason}`);
  }
  console.error("\nRemove the dependency, find an alternative, or document an exception via ADR (§13.2).");
  process.exit(1);
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)([-._].*)?$/i;

function licenseTexts(dir) {
  if (!dir || !existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim())
    .filter(Boolean);
}

function notices() {
  const packages = collect();
  const groups = new Map(); // text → package labels
  const missing = [];

  for (const p of packages) {
    const label = `${p.name} ${p.version} (${p.ecosystem})`;
    const texts = licenseTexts(p.dir);
    if (texts.length === 0) missing.push(p);
    for (const text of texts) {
      if (!groups.has(text)) groups.set(text, []);
      groups.get(text).push(label);
    }
  }

  const lines = [
    "# Third-party notices",
    "",
    "<!-- Generated by `pnpm licenses:notices` (scripts/licenses.mjs). Do not edit by hand. -->",
    "",
    "This product is licensed under GPL-3.0-or-later and includes the following third-party software.",
    "",
    "## Components",
    "",
    "| Component | Version | Ecosystem | Licence |",
    "|---|---|---|---|",
    ...packages.map((p) => `| ${p.name} | ${p.version} | ${p.ecosystem} | ${p.license} |`),
    "",
    "## Licence texts",
    "",
  ];

  let i = 1;
  for (const [text, users] of groups) {
    lines.push(`### Text ${i++}`, "", `Used by: ${users.join(", ")}`, "", "```text", text, "```", "");
  }

  if (missing.length) {
    lines.push(
      "## Components without a bundled licence file",
      "",
      "These packages declare an SPDX licence but ship no licence file; the standard text applies",
      "(see https://spdx.org/licenses/).",
      "",
      ...missing.map((p) => `- ${p.name} ${p.version} (${p.ecosystem}): ${p.license}`),
      "",
    );
  }

  writeFileSync(join(ROOT, "THIRD_PARTY_NOTICES.md"), lines.join("\n"), "utf8");
  console.log(
    `Wrote THIRD_PARTY_NOTICES.md: ${packages.length} components, ${groups.size} distinct licence texts, ${missing.length} without file.`,
  );
}

const command = process.argv[2];
if (command === "check") check();
else if (command === "notices") notices();
else {
  console.error("Usage: node scripts/licenses.mjs <check|notices>");
  process.exit(2);
}
